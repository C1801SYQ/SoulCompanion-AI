'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { checkBundle, measureBundle, BUDGET } = require('./check_weapp_bundle.cjs');
const root = path.resolve(__dirname, '../.test-artifacts/weapp-bundle-unit');
fs.mkdirSync(path.join(root, 'pages/legacy'), { recursive: true });
fs.writeFileSync(path.join(root, 'app.json'), JSON.stringify({ pages: ['pages/community/index'], subPackages: [{ root: 'pages/legacy', pages: ['index'] }], lazyCodeLoading: 'requiredComponents' }));
fs.writeFileSync(path.join(root, 'app.js'), 'main');
fs.writeFileSync(path.join(root, 'pages/legacy/index.js'), 'private shared tools');
const result = measureBundle(root);
assert.equal(result.totalBytes - result.mainBytes, Buffer.byteLength('private shared tools'));
assert.equal(result.subpackages[0].bytes, Buffer.byteLength('private shared tools'));
checkBundle(result);
assert.throws(() => checkBundle({ ...result, mainBytes: BUDGET.main + 1 }));
assert.throws(() => checkBundle({ ...result, totalBytes: BUDGET.total + 1 }));
assert.throws(() => checkBundle({ ...result, subpackages: [{ bytes: BUDGET.subpackage + 1 }] }));
assert.throws(() => checkBundle({ ...result, lazyCodeLoading: null }));
fs.writeFileSync(path.join(root, 'app.json'), JSON.stringify({ subPackages: [{ root: '../private', pages: ['index'] }] }));
assert.throws(() => measureBundle(root));
fs.writeFileSync(path.join(root, 'app.json'), JSON.stringify({ subPackages: [{ root: 'pages/legacy', independent: true }] }));
assert.throws(() => measureBundle(root));
console.log('WeChat package budget regression checks: 8 passed.');
